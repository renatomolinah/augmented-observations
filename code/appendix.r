# A.2 — implied retrospective value under each outcome -----------------------
# Use the three preferred-spec coefficients above to compute the dollar value of
# augmented observations under each notion of value, summed over the same
# 2017--2020 hurricane-force / 3-day-lead county-storm panel as the main
# Stage 3 valuation in NOAA_report.r.

denial_full <- as_tibble(data.table::fread(denial_path))
hf3 <- denial_full |>
  filter(lead_days == 3, wind_obs > 33, !is.na(augmented_obs))

m_delta_app <- feols(wind_fc_sd ~ augmented_obs | county + name,
                     data = hf3, vcov = ~name)
delta_app      <- abs(coef(m_delta_app)["augmented_obs"])
sigma_bar_app  <- hf3 |>
  filter(augmented_obs == 1) |>
  summarise(s = mean(wind_fc_sd, na.rm = TRUE)) |>
  pull(s)
delta_sigma_sq <- (sigma_bar_app + delta_app)^2 - sigma_bar_app^2

# pop / GDP are constant within (county, year)
county_attr <- voi_load() |>
  distinct(county, year, population, gdp)
val <- hf3 |>
  left_join(county_attr, by = c("county", "year"))
# Hurricane Maria's Puerto Rico counties are absent from the continental VOI damage
# panel, so they carry the uniform total-cost per-county value (which needs no county
# attributes) but lack the GDP and population required by the scaled notions. The
# total-cost aggregate therefore spans all hurricane-force county-storms, matching the
# Section \ref{sec:results} headline; the cost/GDP and cost-per-capita columns are
# evaluated on the continental county-storms where economic attributes are observed.

get_hurr <- function(m) {
  ce <- as.matrix(m)
  unname(ce[grep("categoryHurricane", rownames(ce)), "Estimate"])
}
b_tot <- get_hurr(mA2_tot)   # $M     per (m/s)^2
b_gdp <- get_hurr(mA2_gdp)   # %      per (m/s)^2 (LHS scaled by 100)
b_pc  <- get_hurr(mA2_pc)    # $/pers per (m/s)^2

val <- val |>
  mutate(
    v_tot_M = b_tot * delta_sigma_sq,
    v_gdp_M = (b_gdp / 100) * delta_sigma_sq * gdp / 1e3,
    v_pc_M  = b_pc * delta_sigma_sq * population / 1e6
  )

# hf3 carries two rows per county-storm (augmented_obs 0/1, the AO-denied and
# AO-assimilated denial runs); the delta regression uses both, but the dollar
# aggregation must sum over DISTINCT county-storms or it double-counts (124 -> 62).
val_cs   <- val |> distinct(county, name, .keep_all = TRUE)
val_econ <- val_cs |> filter(!is.na(gdp), !is.na(population))
n_all  <- nrow(val_cs)
n_econ <- nrow(val_econ)

agg <- tibble(
  Outcome = c("Total cost (\\$M)",
              "Cost / county GDP (\\%)",
              "Cost per capita (\\$)"),
  beta    = c(b_tot, b_gdp, b_pc),
  per_co  = c(mean(val_cs$v_tot_M),
              mean(val_econ$v_gdp_M),
              mean(val_econ$v_pc_M)),
  total_B = c(sum(val_cs$v_tot_M) / 1000,
              sum(val_econ$v_gdp_M) / 1000,
              sum(val_econ$v_pc_M)  / 1000)
)

# Build the LaTeX directly so the math note (\Delta, \sigma, \bar, \ref) is not
# stripped by kableExtra's footnote() escape pass.
val_tex_str <- sprintf(
'\\begin{table}

\\caption{Implied retrospective social value of augmented observations under three notions of value. \\label{tab:implied_value}}
\\centering
\\begin{adjustbox}{max width = \\textwidth}
\\begin{threeparttable}
\\begin{tabular}[t]{lrrr}
\\toprule
Outcome variable & $\\hat{\\beta}^w_{Hurr}$ & Mean per-county value (\\$M) & Aggregate value 2017--2020 (\\$B)\\\\
\\midrule
Total cost (\\$M) & %.3f & %.2f & %.2f\\\\
Cost / county GDP (\\%%) & %.3f & %.2f & %.2f\\\\
Cost per capita (\\$) & %.3f & %.2f & %.2f\\\\
\\bottomrule
\\end{tabular}
\\begin{tablenotes}
\\small
\\item The total-cost aggregate sums over all %d hurricane-force county-storms including Maria. The cost/GDP and cost-per-capita columns sum over the %d continental county-storms with observed GDP and population.
\\end{tablenotes}
\\end{threeparttable}
\\end{adjustbox}
\\end{table}
',
  b_tot, mean(val_cs$v_tot_M),   sum(val_cs$v_tot_M)   / 1000,
  b_gdp, mean(val_econ$v_gdp_M), sum(val_econ$v_gdp_M) / 1000,
  b_pc,  mean(val_econ$v_pc_M),  sum(val_econ$v_pc_M)  / 1000,
  n_all, n_econ
)
writeLines(val_tex_str, here("output/implied_value.tex"))

cat(sprintf("[Appendix A] aggregate value 2017--2020 (B$): total=%.2f gdp=%.2f pc=%.2f\n",
            agg$total_B[1], agg$total_B[2], agg$total_B[3]))

# A.3 — one-storm-out jackknife on Hurricane beta -----------------------------
top_storms <- c("katrina", "harvey", "sandy", "ian", "ida",
                "michael", "laura", "irma", "wilma", "rita",
                "helene")
jack_rows <- list()
for (s in c("none", top_storms)) {
  d <- if (s == "none") voi_load() else voi_load_drop(s)
  m <- run_conley(spec_col7("total_cost"), d)
  # conleyreg returns a `coeftest` matrix: cols are Estimate / Std. Error / t / Pr(>|t|)
  ce <- as.matrix(m)
  hurr_ix <- grep("categoryHurricane", rownames(ce))
  sub_ix  <- grep("categoryTropical Storm", rownames(ce))
  jack_rows[[s]] <- tibble(
    dropped = s,
    n_storms = length(unique(d$hurricane)),
    n_rows = nrow(d),
    beta_hurr    = ce[hurr_ix, "Estimate"],
    se_hurr      = ce[hurr_ix, "Std. Error"],
    beta_subhurr = ce[sub_ix,  "Estimate"],
    se_subhurr   = ce[sub_ix,  "Std. Error"]
  )
}
jack_df <- bind_rows(jack_rows) |>
  mutate(across(c(beta_hurr, se_hurr, beta_subhurr, se_subhurr), \(x) sprintf("%.3f", x))) |>
  mutate(
    dropped = if_else(dropped == "none", "(none)", str_to_title(dropped)),
    n_rows  = format(n_rows, big.mark = ",")
  )

jack_disp <- jack_df |>
  transmute(
    Dropped        = dropped,
    `Obs.`         = n_rows,
    `$\\beta_2$: Hurricane` = paste0(beta_hurr, " (", se_hurr, ")"),
    `$\\beta_2$: Sub-Hurr.` = paste0(beta_subhurr, " (", se_subhurr, ")")
  )

jack_tex <- kbl(
  jack_disp,
  format    = "latex",
  booktabs  = TRUE,
  escape    = FALSE,
  caption   = "One-storm-out jackknife of the marginal cost of forecast error. \\label{tab:cost_jackknife}",
  linesep   = "",
  align     = c("l", "r", "r", "r")
) |>
  footnote(
    general = "Preferred-specification estimate after dropping each storm, with Conley spatial HAC standard errors (400 km cutoff) in parentheses.",
    general_title = "",
    threeparttable = TRUE,
    fixed_small_size = TRUE,
    escape = FALSE
  )
writeLines(as.character(jack_tex), here("output/cost_jackknife.tex"))
add_adjust_box(here("output/cost_jackknife.tex"))

