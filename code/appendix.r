# ==============================================================================
# Appendix C — per-storm decomposition of the retrospective total
# ==============================================================================
# Re-derive Stage 3 valuation per storm using the same beta and delta the main
# report uses.

# Recompute beta on full panel (Conley HAC)
m_beta <- run_conley(spec_col7("total_cost"), voi_load())
beta_hurr <- unname(coef(m_beta)[grep("categoryHurricane", names(coef(m_beta)))])

# Delta and baseline sigma from main report's Stage 2 sample (Maria included)
reg_data <- denial_with_maria |> filter(lead_days == 3, wind_obs > 33)
m_delta  <- feols(wind_fc_sd ~ augmented_obs | county + name,
                  data = reg_data, vcov = ~name)
delta <- abs(coef(m_delta)["augmented_obs"])
sigma_bar <- reg_data |> filter(augmented_obs == 1) |>
  summarise(s = mean(wind_fc_sd, na.rm = TRUE)) |> pull(s)
delta_sigma_sq <- (sigma_bar + delta)^2 - sigma_bar^2
value_per_county <- beta_hurr * delta_sigma_sq

# Storm-dependent valuation: each storm uses its OWN baseline forecast SD
# sigma_{ALL,h} (the storm-mean ex-ante SD on the AO-assimilated subset), as in
# eq. 8, rather than the pooled mean. Value is linear in sigma, so the TOTAL is
# unchanged; this reallocates shares toward storms whose forecasts were noisier
# (higher sigma_h => larger per-county value).
per_storm <- reg_data |>
  group_by(name) |>
  summarise(
    affected_counties = n_distinct(county),
    sigma_h = mean(wind_fc_sd[augmented_obs == 1], na.rm = TRUE),
    .groups = "drop"
  ) |>
  mutate(
    value_per_county_h = beta_hurr * ((sigma_h + delta)^2 - sigma_h^2),
    value_M = affected_counties * value_per_county_h,
    share   = value_M / sum(value_M)
  ) |>
  arrange(desc(value_M))

per_storm_disp <- per_storm |>
  transmute(
    Storm = str_to_title(name),
    `HF Counties Affected` = affected_counties,
    `$\\bar{\\sigma}_{\\text{ALL},h}$ (m/s)` = formatC(sigma_h, format = "f", digits = 2),
    `Value (\\$M)` = formatC(value_M, format = "f", digits = 1, big.mark = ","),
    `Share of Total` = sprintf("%.1f\\%%", 100 * share)
  ) |>
  bind_rows(
    tibble(
      Storm = "\\textbf{Total}",
      `HF Counties Affected` = sum(per_storm$affected_counties),
      `$\\bar{\\sigma}_{\\text{ALL},h}$ (m/s)` = "",
      `Value (\\$M)` = sprintf("\\textbf{%s}",
                                formatC(sum(per_storm$value_M),
                                        format = "f", digits = 1, big.mark = ",")),
      `Share of Total` = "\\textbf{100.0\\%}"
    )
  )

C_tex <- kbl(
  per_storm_disp,
  format    = "latex",
  booktabs  = TRUE,
  escape    = FALSE,
  caption   = sprintf("Per-storm decomposition of the \\$%.2fB retrospective social value. \\label{tab:per_storm}", sum(per_storm$value_M) / 1000),
  align     = c("l", "r", "r", "r", "r"),
  linesep   = ""
) |>
  footnote(
    general = sprintf(
      "Each storm's value is its hurricane-force / 3-day-lead county count times $\\\\hat{\\\\beta}^w_{Hurr}\\\\,[(\\\\bar{\\\\sigma}_{\\\\text{ALL},h}+\\\\hat{\\\\delta})^2-\\\\bar{\\\\sigma}_{\\\\text{ALL},h}^2]$, with $\\\\hat{\\\\beta}^w_{Hurr}=%.2f$ and $\\\\hat{\\\\delta}=%.3f$ m/s. The total is invariant to using storm-specific or pooled $\\\\sigma$ because value is linear in $\\\\sigma$.",
      beta_hurr, delta
    ),
    general_title = "",
    threeparttable = TRUE,
    fixed_small_size = TRUE,
    escape = FALSE
  )
writeLines(as.character(C_tex), here("output/per_storm.tex"))
add_adjust_box(here("output/per_storm.tex"))

